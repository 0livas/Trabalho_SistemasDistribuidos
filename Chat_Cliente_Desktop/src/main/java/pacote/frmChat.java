    @SuppressWarnings("unchecked")
    public String msg = "";
    
    public void gerarMsg(){
        this.msg = "";
        this.msg +="<img src='file:" + Util.Avatar + "' width='20' height='20'>";
        this.msg +="<font color='"+ Util.Cor +"' size='3'>" + Util.Nickname + "</font>";
        this.msg +="";
        if(figurinhaSelecionada != null){
            this.msg += "<font color='Black' size='3'>" + "<B> Envia figurinha: </B></font><br>";
            this.msg += "<img src='" + figurinhaSelecionada + "' width='120' height='120'>";
            figurinhaSelecionada = null;
        } else if(Cbox_Modo.getSelectedItem().toString().equals("Fala")){
            this.msg +="<B> Fala: </B>";
            this.msg += Txt_Mensagem.getText();
        } else if(Cbox_Modo.getSelectedItem().toString().equals("Grita")){
            this.msg +="<B><i><u> Grita: </B></i></u>";
            this.msg +="<font color='Red' size='5'>" + Txt_Mensagem.getText().toUpperCase() + "</font>";
        } else if(Cbox_Modo.getSelectedItem().toString().equals("Xinga")){
            this.msg +="<B> Xinga: </B>";
            char[] aux = Txt_Mensagem.getText().toCharArray();
            //System.out.println(Txt_Mensagem.getText()); #DEBUG
            for(int i=0; i<aux.length; i++){
                if(i%5 == 0){
                    aux[i] = '@';
                }
                else if(i%3 == 0){
                    aux[i] = '#';
                }
                else if(i%2 == 0){
                    aux[i] = '!';
                }
            }
            
            String string = String.valueOf(aux);
            Txt_Mensagem.setText(string);
            //System.out.println(Txt_Mensagem.getText()); #DEBUG
            this.msg +="<font color='Green' size='5'>" + Txt_Mensagem.getText() + "</font>";
        }
        this.msg+="<br>";
        this.msg = Menu_EmojiFigurinha.converterEmojis(this.msg);

        try{
            Socket cliente = new Socket(Util.IPServidor, Util.PortaRecepcaoDesktop);
            ObjectOutputStream output = new ObjectOutputStream(cliente.getOutputStream());
            output.flush();
            output.writeUTF(this.msg);
            output.close();
            cliente.close();
        }
        catch(Exception E){
            JOptionPane.showMessageDialog(null, "Erro no Cliente frmChat::gerarMsg " + E.getMessage());
            E.printStackTrace();
        }
    }
